def _legs(rows, shift):
    out = list(rows)
    for y in range(15, 23):
        r = list(out[y])
        if shift:
            r = list(out[y][1:] + '.') if (y % 2) else list('.' + out[y][:-1])
        out[y] = ''.join(r)
    return out


