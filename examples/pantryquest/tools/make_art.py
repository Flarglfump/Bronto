def check(name, rows):
    w = len(rows[0])
    for i, r in enumerate(rows):
        if len(r) != w:
            raise SystemExit('%s row %d is %d wide, not %d: %r' % (name, i, len(r), w, r))
        for ch in r:
            if ch not in PALETTE:
                raise SystemExit('%s row %d: unknown colour %r' % (name, i, ch))


def pixels_of(rows, under=None):
    out = []
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            c = PALETTE[ch]
            if c is None:
                out.append(under[y * len(r) + x] if under else (0, 0, 0, 0))
            else:
                out.append((c[0], c[1], c[2], 255))
    return out


def write_bmp(path, w, h, px):
    """32-bit top-down BMP with an alpha mask (as br_image_save_bmp writes)."""
    header = 14 + 108
    data = bytearray()
    for (r, g, b, a) in px:
        data += bytes((b, g, r, a))
    info = struct.pack('<IiiHHIIiiII', 108, w, -h, 1, 32, 3, len(data), 2835, 2835, 0, 0)
    info += struct.pack('<IIIII', 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000, 0x73524742)
    info += bytes(108 - len(info))
    head = b'BM' + struct.pack('<IHHI', header + len(data), 0, 0, header)
    with open(path, 'wb') as f:
        f.write(head + info + data)


def write_png(path, w, h, px):
    raw = b''.join(b'\x00' + bytes(sum((list(p) for p in px[y * w:(y + 1) * w]), [])) for y in range(h))
    def chunk(t, d):
        c = struct.pack('>I', len(d)) + t + d
        return c + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) +
                chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def tileset(names, ground_name):
    """The tiles side by side (16 a row); a tile's transparent pixels show the ground tile."""
    ground = pixels_of(S['tile_' + ground_name])
    per_row = 16
    rows_n = (len(names) + per_row - 1) // per_row
    w, h = per_row * 16, rows_n * 16
    img = [(0, 0, 0, 0)] * (w * h)
    for i, n in enumerate(names):
        px = pixels_of(S['tile_' + n], ground)
        ox, oy = (i % per_row) * 16, (i // per_row) * 16
        for y in range(16):
            for x in range(16):
                img[(oy + y) * w + ox + x] = px[y * 16 + x]
    return w, h, img


def main():
    os.makedirs(ART, exist_ok=True)
    for name, rows in S.items():
        check(name, rows)
    written = 0
    for name, rows in S.items():
        if name.startswith('tile_'):
            continue
        write_bmp(os.path.join(ART, name + '.bmp'), len(rows[0]), len(rows), pixels_of(rows))
        written += 1
    for file, names, ground in (('tiles_overworld.bmp', OVERWORLD_TILES, 'ground'),
                                ('tiles_dungeon.bmp', DUNGEON_TILES, 'd_floor')):
        w, h, img = tileset(names, ground)
        write_bmp(os.path.join(ART, file), w, h, img)
        written += 1
    # the window and taskbar icon: Pip, 4x
    hero = pixels_of(S['hero_down_0'])
    big = [hero[(y // 4) * 16 + x // 4] for y in range(64) for x in range(64)]
    write_bmp(os.path.join(ART, 'icon.bmp'), 64, 64, big)
    print('make_art: wrote %d images to %s' % (written + 1, os.path.normpath(ART)))

    if '--preview' in sys.argv:
        out = sys.argv[sys.argv.index('--preview') + 1]
        names = [n for n in S]
        cell, cols = 36, 12
        rows_n = (len(names) + cols - 1) // cols
        W, H = cols * cell * 2, rows_n * cell * 2
        img = [(40, 44, 52, 255)] * (W * H)
        for i, n in enumerate(names):
            rows = S[n]
            px = pixels_of(rows)
            w, h = len(rows[0]), len(rows)
            ox, oy = (i % cols) * cell * 2 + 2, (i // cols) * cell * 2 + 2
            for y in range(h):
                for x in range(w):
                    p = px[y * w + x]
                    if p[3] == 0:
                        continue
                    for dy in range(2 if h > 16 else 4):
                        for dx in range(2 if w > 16 else 4):
                            sx, sy = ox + x * (2 if w > 16 else 4) + dx, oy + y * (2 if h > 16 else 4) + dy
                            if sx < W and sy < H:
                                img[sy * W + sx] = p
        write_png(out, W, H, img)
        print('make_art: preview in', out)


if __name__ == '__main__':
    main()
